const normalize=(text:string)=>text.normalize("NFD").replace(/[\u0300-\u036f]/g,"").toLowerCase().replace(/[^a-z0-9\s]/g," ").replace(/\s+/g," ").trim();
const stop=new Set("el la los las un una unos unas de del a al en es son se y o que cual cuales como por para con lo le les me nos te su sus este esta estos estas ese esa esos esas proyecto trabajo sobre ustedes pueden puedes favor porfavor quiero quisiera saber diganme dime cuentame hablame explicame".split(" "));
const words=(text:string)=>new Set(normalize(text).split(" ").filter(w=>w&&!stop.has(w)));
const topicPatterns:[RegExp,string][]=[[/colegio.*sustentable|maqueta|panel.*solar/,"colegio"],[/reutilizacion natural|papel|hojas/,"papel"],[/arte reciclado|tortuga|alcancia|laberinto/,"arte"],[/mural/,"mural"],[/pulpo|octavio/,"pulpo"],[/impacto ambiental.*(?:celular|telefono)|basura tecnologica|residuos electronicos/,"residuos"],[/museo vivo|museo virtual/,"museo"],[/\balma\b|chajnantor/,"alma"],[/telescop/,"telescopio"],[/adelina|gutierrez/,"adelina"],[/salud mental|estres/,"salud"],[/emocion|rabia|frustracion/,"emociones"],[/uso excesivo|pantalla|celular|telefono/,"pantallas"],[/droga/,"drogas"],[/alimentacion|colacion|ultraprocesado/,"alimentacion"]];
function topicOf(text:string){return topicPatterns.find(([pattern])=>pattern.test(normalize(text)))?.[1]}

/** Conservative retrieval: exact curated variants, then high-overlap and unambiguous matches. */
export function fairKnowledgeAnswer(messages:readonly Message[]):string|null {
 const question=messages.at(-1)?.content||"",normalized=normalize(question);
 // Personal health advice and unrelated compound questions must continue to the normal handling.
 if(/\b(?:dosis|medicamento|diagnostico|diagnosticar|suicid|autoles|intoxica|sobredosis)\w*/.test(normalized))return null;
 const exact=FAIR_KNOWLEDGE.find(e=>[e.question,...e.variants].some(q=>normalize(q)===normalized));
 if(exact)return exact.answer;
 const query=words(question);if(query.size<2)return null;
 let topic=topicOf(question);
 if(!topic&&/\b(?:ese|esa|eso|este|esta|lo|sus)\b|^(?:y )?(?:como funciona|que materiales|como construyeron)/.test(normalized)){
  topic=messages.slice(0,-1).filter(m=>m.role==="user").map(m=>topicOf(m.content)).findLast(Boolean);
 }
 const ranked=FAIR_KNOWLEDGE.filter(e=>!topic||e.topic===topic).map(e=>{
  const score=Math.max(...[e.question,...e.variants].map(q=>{
   const candidate=words(q),overlap=[...query].filter(w=>candidate.has(w)).length;
   const coverage=overlap/query.size,recall=overlap/candidate.size;
   return coverage>=.85&&recall>=.65?2*coverage*recall/(coverage+recall):0;
  }));
  return {entry:e,score};
 }).sort((a,b)=>b.score-a.score);
 const first=ranked[0],second=ranked[1];
 return first&&first.score>=.8&&first.score-(second?.score||0)>=.12?first.entry.answer:null;
}
